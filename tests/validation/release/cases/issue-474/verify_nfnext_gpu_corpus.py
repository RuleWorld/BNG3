#!/usr/bin/env python3
"""Independent hardware verification of network-free GPU execution across TIER_NF.

Executes all four required TIER_NF corpus models (motor, simple_system,
localfunc, tlbr) on the selected GPU backend (``metal`` or ``cuda``) with
``mode="graph"`` and compares every observable at every sample time point
against an independent pinned native ``NFsim`` ensemble (using BNG-XML
generated by pinned ``BNG2.pl``) via 4-sigma Welch mean checks and two-sample
KS/DKW distributional bounds, plus deterministic same-device replay and
fail-closed refusal checks.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import math
import platform
import re
import subprocess
import sys
import tempfile
import time
from concurrent.futures import ThreadPoolExecutor
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import numpy as np

REPO = Path(__file__).resolve().parents[5]
if str(REPO) not in sys.path:
    sys.path.insert(0, str(REPO))

import bionetgen  # noqa: E402
from tests.validation import compare  # noqa: E402


@dataclass(frozen=True)
class CorpusCase:
    name: str
    model_rel: str
    t_end: float
    n_steps: int
    n_trajectories: int


TIER_NF_CASES: tuple[CorpusCase, ...] = (
    CorpusCase("motor", "models/flagellar_motor/motor.bngl", 5.0, 5, 256),
    CorpusCase("simple_system", "models/simple_system.bngl", 0.5, 5, 256),
    CorpusCase("localfunc", "models/localfunc.bngl", 5.0, 5, 256),
    CorpusCase("tlbr", "models/tlbr/tlbr.bngl", 10.0, 5, 128),
)


def _sha256_file(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _strip_actions_for_xml(bngl_text: str) -> str:
    if "begin actions" in bngl_text:
        head = bngl_text.split("begin actions", 1)[0]
        if "end model" in head:
            head = head.split("end model", 1)[0] + "end model\n"
        return head + "\nwriteXML()\n"
    cleaned = re.sub(
        r"^\s*(writeXML|simulate_nf|simulate_ode|simulate_ssa|generate_network|writeMfile|writeMexfile)\b.*$",
        "",
        bngl_text,
        flags=re.MULTILINE,
    )
    return cleaned + "\nwriteXML()\n"


def _run_native_nfsim_one(
    nfsim_bin: Path,
    xml_path: Path,
    t_end: float,
    n_steps: int,
    seed: int,
    out_path: Path,
) -> tuple[np.ndarray, list[str]]:
    subprocess.run(
        [
            str(nfsim_bin),
            "-xml",
            str(xml_path),
            "-o",
            str(out_path),
            "-sim",
            str(t_end),
            "-oSteps",
            str(n_steps),
            "-seed",
            str(seed),
        ],
        check=True,
        capture_output=True,
        text=True,
        timeout=120,
    )
    vals, cols = compare.parse_gdat(out_path)
    if vals is None or cols is None:
        raise RuntimeError(f"failed to parse native NFsim output {out_path}")
    return vals, list(cols)


def _compare_distributions(
    native_samples: dict[str, np.ndarray],
    gpu_samples: dict[str, np.ndarray],
    times: list[float],
    *,
    sigma_limit: float = 4.0,
    alpha: float = 1e-4,
) -> dict[str, Any]:
    max_z = 0.0
    max_ks = 0.0
    failures: list[dict[str, Any]] = []
    per_observable: dict[str, dict[str, Any]] = {}

    for col in sorted(native_samples):
        obs_max_z = 0.0
        obs_max_ks = 0.0
        for ti, t_val in enumerate(times):
            a = np.asarray(native_samples[col][:, ti], dtype=np.float64)
            b = np.asarray(gpu_samples[col][:, ti], dtype=np.float64)
            ma, mb = float(np.mean(a)), float(np.mean(b))
            va, vb = float(np.var(a, ddof=1)), float(np.var(b, ddof=1))
            se = math.sqrt(va / len(a) + vb / len(b))
            if se == 0.0:
                z = 0.0 if abs(ma - mb) == 0.0 else float("inf")
            else:
                z = abs(ma - mb) / se

            all_v = np.sort(np.concatenate([a, b]))
            cdf_a = np.searchsorted(np.sort(a), all_v, side="right") / len(a)
            cdf_b = np.searchsorted(np.sort(b), all_v, side="right") / len(b)
            ks = float(np.max(np.abs(cdf_a - cdf_b)))
            ks_crit = math.sqrt(
                -0.5 * math.log(alpha / 2.0) * (1.0 / len(a) + 1.0 / len(b))
            )

            obs_max_z = max(obs_max_z, z)
            obs_max_ks = max(obs_max_ks, ks)
            max_z = max(max_z, z)
            max_ks = max(max_ks, ks)
            if z > sigma_limit or ks > ks_crit:
                failures.append(
                    {
                        "observable": col,
                        "time_index": ti,
                        "time": t_val,
                        "native_mean": ma,
                        "gpu_mean": mb,
                        "z_score": z,
                        "ks": ks,
                        "ks_crit": ks_crit,
                    }
                )
        per_observable[col] = {
            "native_final_mean": float(np.mean(native_samples[col][:, -1])),
            "gpu_final_mean": float(np.mean(gpu_samples[col][:, -1])),
            "max_z": obs_max_z,
            "max_ks": obs_max_ks,
        }

    return {
        "passed": len(failures) == 0,
        "sigma_limit": sigma_limit,
        "ks_alpha": alpha,
        "max_z": max_z,
        "max_ks": max_ks,
        "failures": failures,
        "observables": per_observable,
    }


def run_corpus_verification(
    *,
    backend: str,
    nfsim_bin: Path,
    bng2_pl: Path,
    workers: int = 8,
    base_seed: int = 42,
    native_seed_base: int = 1001,
) -> dict[str, Any]:
    if not nfsim_bin.is_file():
        raise FileNotFoundError(f"Pinned native NFsim binary not found: {nfsim_bin}")
    if not bng2_pl.is_file():
        raise FileNotFoundError(f"Pinned BNG2.pl not found: {bng2_pl}")

    caps = bionetgen.gpu_backend_capabilities()
    backend_cap = next((c for c in caps if c.get("name") == backend), None)
    if not backend_cap or not backend_cap.get("available"):
        raise RuntimeError(
            f"Requested GPU backend '{backend}' is not available: {caps}"
        )

    rev = subprocess.check_output(
        ["git", "-C", str(REPO), "rev-parse", "HEAD"], text=True
    ).strip()
    dirty = bool(
        subprocess.check_output(
            ["git", "-C", str(REPO), "status", "--porcelain"], text=True
        ).strip()
    )

    case_reports: list[dict[str, Any]] = []
    all_passed = True

    with tempfile.TemporaryDirectory(prefix=f"bng3-474-{backend}-") as td:
        td_path = Path(td)
        for case in TIER_NF_CASES:
            model_path = (REPO / case.model_rel).resolve()
            xml_dir = td_path / case.name
            xml_dir.mkdir(parents=True, exist_ok=True)
            work_bngl = xml_dir / f"{case.name}.bngl"
            work_bngl.write_text(
                _strip_actions_for_xml(model_path.read_text(encoding="utf-8")),
                encoding="utf-8",
            )
            subprocess.run(
                ["perl", str(bng2_pl), str(work_bngl)],
                cwd=xml_dir,
                check=True,
                capture_output=True,
                text=True,
                timeout=60,
            )
            xml_path = xml_dir / f"{case.name}.xml"
            if not xml_path.is_file():
                raise RuntimeError(f"BNG2 did not emit XML for {case.name}")

            t0 = time.perf_counter()
            with ThreadPoolExecutor(max_workers=workers) as pool:
                native_runs = list(
                    pool.map(
                        lambda i: _run_native_nfsim_one(
                            nfsim_bin,
                            xml_path,
                            case.t_end,
                            case.n_steps,
                            native_seed_base + i,
                            xml_dir / f"native_{i}.gdat",
                        ),
                        range(case.n_trajectories),
                    )
                )
            native_wall_s = time.perf_counter() - t0
            cols = [c for c in native_runs[0][1] if c != "time"]
            if not cols:
                raise RuntimeError(
                    f"No observables emitted by native NFsim for {case.name}"
                )
            native_samples = {
                c: np.stack(
                    [vals[:, col_list.index(c)] for vals, col_list in native_runs],
                    axis=0,
                )
                for c in cols
            }

            times = [
                float(np.float32(case.t_end * i / case.n_steps))
                for i in range(case.n_steps + 1)
            ]
            model = bionetgen.load(str(model_path))
            t0 = time.perf_counter()
            gpu_res = model.simulate_nfnext_gpu(
                times,
                seed=base_seed,
                batch_size=case.n_trajectories,
                backend=backend,
                mode="graph",
                max_events=50_000_000,
            )
            gpu_wall_s = time.perf_counter() - t0

            # Deterministic same-device replay check on 16 trajectories
            rep1 = model.simulate_nfnext_gpu(
                times,
                seed=base_seed + 999,
                batch_size=16,
                backend=backend,
                mode="graph",
                max_events=50_000_000,
            )
            rep2 = model.simulate_nfnext_gpu(
                times,
                seed=base_seed + 999,
                batch_size=16,
                backend=backend,
                mode="graph",
                max_events=50_000_000,
            )
            deterministic_replay = all(
                np.array_equal(rep1.observables[c], rep2.observables[c]) for c in cols
            )

            gpu_samples = {c: gpu_res.observables[c] for c in cols}
            dist = _compare_distributions(native_samples, gpu_samples, times)
            case_ok = bool(dist["passed"] and deterministic_replay)
            if not case_ok:
                all_passed = False

            total_events = int(np.sum(gpu_res.event_counts))
            case_reports.append(
                {
                    "model": case.name,
                    "model_rel": case.model_rel,
                    "model_sha256": _sha256_file(model_path),
                    "xml_sha256": _sha256_file(xml_path),
                    "t_end": case.t_end,
                    "n_steps": case.n_steps,
                    "n_trajectories": case.n_trajectories,
                    "backend": gpu_res.backend,
                    "device": gpu_res.device,
                    "gpu_seed": base_seed,
                    "native_seed_range": [
                        native_seed_base,
                        native_seed_base + case.n_trajectories - 1,
                    ],
                    "native_wall_s": round(native_wall_s, 4),
                    "native_workers": workers,
                    "gpu_wall_s": round(gpu_wall_s, 4),
                    "gpu_dispatch_wait_ms": round(
                        float(gpu_res.dispatch_wait_time_ms), 3
                    ),
                    "gpu_setup_ms": round(float(gpu_res.setup_time_ms), 3),
                    "gpu_device_memory_bytes": int(gpu_res.device_memory_bytes),
                    "gpu_total_events": total_events,
                    "gpu_events_per_sec": (
                        round(total_events / gpu_wall_s, 1) if gpu_wall_s > 0 else 0.0
                    ),
                    "speedup_vs_native_workers": (
                        round(native_wall_s / gpu_wall_s, 2) if gpu_wall_s > 0 else 0.0
                    ),
                    "deterministic_replay": deterministic_replay,
                    "distribution": dist,
                    "passed": case_ok,
                }
            )

    return {
        "schema_version": 1,
        "kind": "issue474-nfnext-gpu-corpus-receipt",
        "backend": backend,
        "device": backend_cap.get("detail"),
        "platform": platform.platform(),
        "python": platform.python_version(),
        "source_revision": rev,
        "source_dirty": dirty,
        "oracle_nfsim_sha256": _sha256_file(nfsim_bin),
        "oracle_bng2_sha256": _sha256_file(bng2_pl),
        "tier": "TIER_NF",
        "case_count": len(case_reports),
        "passed_count": sum(1 for r in case_reports if r["passed"]),
        "result": "pass" if all_passed else "fail",
        "cases": case_reports,
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--backend", choices=("metal", "cuda"), required=True)
    parser.add_argument("--nfsim-bin", type=Path, required=True)
    parser.add_argument("--bng2-pl", type=Path, required=True)
    parser.add_argument("--workers", type=int, default=8)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args(argv)

    report = run_corpus_verification(
        backend=args.backend,
        nfsim_bin=args.nfsim_bin.resolve(),
        bng2_pl=args.bng2_pl.resolve(),
        workers=args.workers,
    )
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(
        json.dumps(report, indent=2, sort_keys=True) + "\n", encoding="utf-8"
    )
    for c in report["cases"]:
        print(
            f"[{c['model']:13s}] backend={c['backend']} device={c['device']!r} "
            f"n={c['n_trajectories']} native={c['native_wall_s']:.2f}s "
            f"gpu={c['gpu_wall_s']:.3f}s speedup={c['speedup_vs_native_workers']:.1f}x "
            f"max_z={c['distribution']['max_z']:.2f} "
            f"max_ks={c['distribution']['max_ks']:.4f} "
            f"replay={c['deterministic_replay']} PASS={c['passed']}"
        )
    print(
        f"RESULT={report['result']} ({report['passed_count']}/{report['case_count']})"
    )
    return 0 if report["result"] == "pass" else 1


if __name__ == "__main__":
    raise SystemExit(main())
