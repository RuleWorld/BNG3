"""Issue #161: a valid bond may connect *instances* with the same site type.

The API-visible structural oracle is the independently authored BNGL bond
pattern, not the Multi XML representation or product generated by Atomizer.
"""

import re

import pytest
import libsbml
import bionetgen
from bionetgen.atomizer.modern import Atomizer, SBMLParser

HOMODIMER = """begin model
begin parameters
  k 0.04
end parameters
begin compartments
  cell 3 0.5
end compartments
begin molecule types
  A(b)
end molecule types
begin seed species
  @cell:A(b) 10
end seed species
begin reaction rules
  bind: @cell:A(b) + @cell:A(b) -> @cell:A(b!1).A(b!1) k
end reaction rules
end model
"""


@pytest.mark.parametrize("atomize", [False, True])
def test_homodimer_with_identical_binding_site_types_reimports(atomize, tmp_path):
    authored = tmp_path / "homodimer.bngl"
    authored.write_text(HOMODIMER, encoding="utf-8")
    multi_xml = bionetgen.load(str(authored)).sbml_multi()
    doc = libsbml.readSBMLFromString(multi_xml)
    assert doc.getNumErrors() == 0, doc.getErrorLog().toString()
    parsed = SBMLParser().parse(multi_xml)
    assert parsed.multi_executable
    # Both A molecules must survive; this cannot be satisfied by a
    # placeholder molecule or a single self-bonded component.
    assert any(
        pattern.count("A(") == 2 and "!1" in pattern
        for pattern in parsed.multi_species_patterns.values()
    )
    imported = Atomizer(atomize=atomize, quiet_mode=True).atomize(multi_xml)
    assert imported.success, imported.error
    reaction_lines = [line for line in imported.bngl.splitlines() if "->" in line]
    normalized = re.sub(r"@[A-Za-z_][A-Za-z0-9_]*::?", "", "\n".join(reaction_lines))
    normalized = normalized.replace("M_A(", "A(")
    assert any(
        "A(b!1).A(b!1)" in line.split("->", 1)[1] for line in normalized.splitlines()
    )
