"""Issue #161: a valid bond may connect *instances* with the same site type.

The API-visible structural oracle is the independently authored BNGL bond
pattern, not the Multi XML representation or product generated by Atomizer.
"""

import re
import xml.etree.ElementTree as ET

import pytest
import libsbml
import bionetgen
from bionetgen.atomizer.modern import Atomizer, SBMLParser

HOMODIMER = """begin model
begin parameters
  k 0.04
end parameters
begin compartments
  cell 3 0.5
end compartments
begin molecule types
  A(b)
end molecule types
begin seed species
  @cell:A(b) 10
end seed species
begin reaction rules
  bind: @cell:A(b) + @cell:A(b) -> @cell:A(b!1).A(b!1) k
end reaction rules
end model
"""


def _in_species_type_bond_site_type_ids(xml):
    multi_ns = "http://www.sbml.org/sbml/level3/version1/multi/version1"
    q = lambda name: f"{{{multi_ns}}}{name}"
    root = ET.fromstring(xml)
    species_types = {
        item.get(q("id")): item
        for item in root.findall(f".//{q('listOfSpeciesTypes')}/*")
        if item.get(q("id"))
    }
    binding_site_types = {
        item.get(q("id")) for item in root.findall(f".//{q('bindingSiteSpeciesType')}")
    }

    def resolve(type_id, component_id):
        species_type = species_types[type_id]
        instances = species_type.find(q("listOfSpeciesTypeInstances"))
        if instances is not None:
            for instance in instances.findall(q("speciesTypeInstance")):
                if instance.get(q("id")) == component_id:
                    return instance.get(q("speciesType"))
        indexes = species_type.find(q("listOfSpeciesTypeComponentIndexes"))
        if indexes is not None:
            for index in indexes.findall(q("speciesTypeComponentIndex")):
                if index.get(q("id")) != component_id:
                    continue
                parent_id = index.get(q("identifyingParent"))
                parent = next(
                    item
                    for item in instances.findall(q("speciesTypeInstance"))
                    if item.get(q("id")) == parent_id
                )
                return resolve(parent.get(q("speciesType")), index.get(q("component")))
        raise AssertionError(f"cannot resolve Multi component {type_id}/{component_id}")

    resolved = []
    for type_id, species_type in species_types.items():
        bonds = species_type.find(q("listOfInSpeciesTypeBonds"))
        if bonds is None:
            continue
        for bond in bonds.findall(q("inSpeciesTypeBond")):
            endpoints = tuple(
                resolve(type_id, bond.get(q(attribute)))
                for attribute in ("bindingSite1", "bindingSite2")
            )
            assert all(endpoint in binding_site_types for endpoint in endpoints)
            resolved.append(endpoints)
    return resolved


@pytest.mark.parametrize("atomize", [False, True])
def test_homodimer_with_identical_binding_site_types_reimports(atomize, tmp_path):
    authored = tmp_path / "homodimer.bngl"
    authored.write_text(HOMODIMER, encoding="utf-8")
    multi_xml = bionetgen.load(str(authored)).sbml_multi()
    doc = libsbml.readSBMLFromString(multi_xml)
    assert doc.getNumErrors() == 0, doc.getErrorLog().toString()
    doc.checkConsistency()
    consistency_errors = [
        doc.getError(index).getErrorId()
        for index in range(doc.getNumErrors())
        if doc.getError(index).getSeverity() >= libsbml.LIBSBML_SEV_ERROR
    ]
    assert consistency_errors == [], doc.getErrorLog().toString()
    # Multi §3.13.2 forbids an InSpeciesTypeBond whose endpoints ultimately
    # reference the same BindingSiteSpeciesType object. libSBML's validator
    # does not report this case, so check the endpoint type identities directly.
    bonds = _in_species_type_bond_site_type_ids(multi_xml)
    assert bonds
    assert all(left != right for left, right in bonds)
    parsed = SBMLParser().parse(multi_xml)
    assert parsed.multi_executable
    # Both A molecules must survive; this cannot be satisfied by a
    # placeholder molecule or a single self-bonded component.
    assert any(
        pattern.count("A(") == 2 and "!1" in pattern
        for pattern in parsed.multi_species_patterns.values()
    )
    imported = Atomizer(atomize=atomize, quiet_mode=True).atomize(multi_xml)
    assert imported.success, imported.error
    reaction_lines = [line for line in imported.bngl.splitlines() if "->" in line]
    normalized = re.sub(r"@[A-Za-z_][A-Za-z0-9_]*::?", "", "\n".join(reaction_lines))
    normalized = normalized.replace("M_A(", "A(")
    assert any(
        "A(b!1).A(b!1)" in line.split("->", 1)[1] for line in normalized.splitlines()
    )
