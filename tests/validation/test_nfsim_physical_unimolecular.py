RUNS = 200
BASE_SEED = 1001
INITIAL_A = 100
RATE_PER_SECOND = 0.5
END_TIME = 1.0
BIMOLECULAR_INITIAL = 10
BIMOLECULAR_COUNT_RATE = 0.05
SYMMETRIC_MOLECULES = 10
SYMMETRIC_BINDING_RATE = 0.1
SYMMETRIC_RUNS = 200
SYMMETRIC_BASE_SEED = 7300
SYMMETRIC_END_TIME = 1.0
ROOT = Path(__file__).resolve().parents[2]


def _physical_bng3_source() -> str:
    return """begin model
  setOption("units", "strict")
  begin units
    timeunits second
  end units
  begin parameters
    k = 0.5 [second^-1]
    Vc = 1 [fL]
  end parameters
  begin compartments
    cell 3 Vc [fL]
  end compartments
  begin molecule types
    A()
    B()
  end molecule types
  begin seed species
    A()@cell 100
    B()@cell 0
  end seed species
  begin observables
    Molecules A_count A()@cell
    Molecules B_count B()@cell
  end observables
  begin reaction rules
    convert: A()@cell -> B()@cell k
  end reaction rules
end model
"""


def _independent_bng2_source() -> str:
    # Same count-process law authored independently for BNG2. NFsim consumes
    # this BNG2-produced XML; no BNG3-generated XML is used as the oracle.
    return """begin model
begin parameters
    k 0.5
end parameters
begin compartments
    cell 3 1
end compartments
begin molecule types
    A()
    B()
end molecule types
begin seed species
    A()@cell 100
    B()@cell 0
end seed species
begin observables
    Molecules A_count A()@cell
    Molecules B_count B()@cell
end observables
begin reaction rules
    convert: A()@cell -> B()@cell k
end reaction rules
end model
generate_network({overwrite=>1})
writeXML()
"""


def _physical_bimolecular_source(volume_femtoliters: float = 1.0) -> str:
    # In 1 fL, 3.01107038e7 M^-1 s^-1 converts to
    # 0.05 item^-1 s^-1: k_count = k_physical / (N_A * V).
    return f"""begin model
  setOption("units", "strict")
  setOption("NumberPerQuantityUnit", 6.02214076e23)
  begin units
    timeunits second
  end units
  begin parameters
    k = 3.01107038e7 [M^-1/second]
    Vc = {volume_femtoliters} [fL]
  end parameters
  begin compartments
    cell 3 Vc [fL]
  end compartments
  begin molecule types
    A()
    B()
    C()
  end molecule types
  begin seed species
    A()@cell {BIMOLECULAR_INITIAL}
    B()@cell {BIMOLECULAR_INITIAL}
    C()@cell 0
  end seed species
  begin observables
    Molecules A_count A()@cell
    Molecules B_count B()@cell
    Molecules C_count C()@cell
  end observables
  begin reaction rules
    combine: A()@cell + B()@cell -> C()@cell k
  end reaction rules
end model
"""


def _independent_bng2_bimolecular_source() -> str:
    # This is a separately authored count-process law. NFsim consumes BNG2's
    # XML for this model, not XML generated by BNG3.
    return f"""begin model
begin parameters
  k_count {BIMOLECULAR_COUNT_RATE}
end parameters
begin compartments
  cell 3 1
end compartments
begin molecule types
  A()
  B()
  C()
end molecule types
begin seed species
  A()@cell {BIMOLECULAR_INITIAL}
  B()@cell {BIMOLECULAR_INITIAL}
  C()@cell 0
end seed species
begin observables
  Molecules A_count A()@cell
  Molecules B_count B()@cell
  Molecules C_count C()@cell
end observables
begin reaction rules
  combine: A()@cell + B()@cell -> C()@cell k_count
end reaction rules
end model
generate_network({{overwrite=>1}})
writeXML()
"""


def _symmetric_dimer_source() -> str:
    return f"""begin model
begin parameters
  kon {SYMMETRIC_BINDING_RATE}
end parameters
begin molecule types
  A(b)
end molecule types
begin seed species
  A(b) {SYMMETRIC_MOLECULES}
end seed species
begin observables
  Species Dimer A(b!1).A(b!1)
  Molecules Bound A(b!+)
end observables
begin reaction rules
  bind: A(b) + A(b) -> A(b!1).A(b!1) kon
end reaction rules
end model
"""


def _assert_symmetric_dimer_marginal(counts: list[int]) -> None:
    """Check the exact homodimer count CTMC, with one observation per run.

    BNG2's independently generated NET must encode two identical reactants
    with a 0.5*kon coefficient. Applying that coefficient to the number of
    ordered distinct molecule pairs gives the analytic propensity
    kon * choose(n_free, 2). This independent finite-state generator uses
    that unordered-pair law directly.
    """
    states = SYMMETRIC_MOLECULES // 2 + 1
    generator = np.zeros((states, states), dtype=float)
    for dimers in range(states - 1):
        free_molecules = SYMMETRIC_MOLECULES - 2 * dimers
        propensity = SYMMETRIC_BINDING_RATE * free_molecules * (free_molecules - 1) / 2
        generator[dimers, dimers] = -propensity
        generator[dimers, dimers + 1] = propensity
    initial = np.zeros(states, dtype=float)
    initial[0] = 1.0
    expected_cdf = np.cumsum(expm(generator.T * SYMMETRIC_END_TIME) @ initial)
    observed_cdf = np.cumsum(np.bincount(counts, minlength=states) / SYMMETRIC_RUNS)
    # One DKW bound at alpha=0.005 for the independent 200-run endpoint sample.
    epsilon = math.sqrt(math.log(2.0 / 0.005) / (2.0 * SYMMETRIC_RUNS))
    assert np.max(np.abs(observed_cdf - expected_cdf)) <= epsilon


def _a_count(trajectory_data, columns):
    assert "A_count" in columns
    assert "B_count" in columns
    a = trajectory_data[-1, columns.index("A_count")]
    b = trajectory_data[-1, columns.index("B_count")]
    assert a + b == INITIAL_A
    return int(a)


def _assert_binomial_count_marginal(counts: list[int]) -> None:
    # At t=1, the source law is Binomial(100, exp(-k*t)). Compare its full
    # endpoint CDF with the 200 independent trajectories. DKW allocates
    # alpha=0.005 to each engine, so the two-engine family-wise false-rejection
    # bound is at most 0.01. Each replicate is treated as one bounded [0, 100]
    # observation; no independence between molecules within a trajectory is
    # assumed by the test.
    survival = math.exp(-RATE_PER_SECOND * END_TIME)
    probability = (1.0 - survival) ** INITIAL_A
    probabilities = [probability]
    for count in range(INITIAL_A):
        probability *= (INITIAL_A - count) / (count + 1) * survival / (1.0 - survival)
        probabilities.append(probability)
    expected_cdf = np.cumsum(probabilities)
    observed_cdf = np.cumsum(np.bincount(counts, minlength=INITIAL_A + 1) / RUNS)
    epsilon = math.sqrt(math.log(2.0 / 0.005) / (2.0 * RUNS))
    assert np.max(np.abs(observed_cdf - expected_cdf)) <= epsilon


def _assert_bimolecular_ctmc_marginal(converted_counts: list[int]) -> None:
    # A+B -> C is a pure-birth chain in C with rate
    # q*(N-C)^2, q=k/(N_A*V). Compute its exact endpoint law from the
    # finite-state generator; each replicate contributes one observation.
    states = BIMOLECULAR_INITIAL + 1
    generator = np.zeros((states, states), dtype=float)
    for converted in range(BIMOLECULAR_INITIAL):
        remaining = BIMOLECULAR_INITIAL - converted
        propensity = BIMOLECULAR_COUNT_RATE * remaining * remaining
        generator[converted, converted] = -propensity
        generator[converted, converted + 1] = propensity
    initial = np.zeros(states, dtype=float)
    initial[0] = 1.0
    expected_probabilities = expm(generator.T * END_TIME) @ initial
    expected_cdf = np.cumsum(expected_probabilities)
    observed_cdf = np.cumsum(np.bincount(converted_counts, minlength=states) / RUNS)
    epsilon = math.sqrt(math.log(2.0 / 0.005) / (2.0 * RUNS))
    assert np.max(np.abs(observed_cdf - expected_cdf)) <= epsilon


@pytest.mark.nf
@pytest.mark.slow
def test_physical_unimolecular_rate_matches_independent_native_count_law(
    api, tmp_path, monkeypatch
):
    configured_bng2 = os.environ.get("BNG2_PERL")
    require_oracle(
        bool(configured_bng2) and Path(configured_bng2).is_file(),
        "independent BNG2 XML translation requires explicit BNG2_PERL",
    )
    require_oracle(oracle_nfsim.nfsim_available(), "set independent NFSIM_BIN")

    monkeypatch.delenv("BNG_NFSIM_FORCE_XML", raising=False)
    monkeypatch.delenv("BNG_NFSIM_ALLOW_XML_FALLBACK", raising=False)
    physical_source = tmp_path / "physical_unimolecular.bngl"
    physical_source.write_text(_physical_bng3_source(), encoding="utf-8")

    bng2_source = tmp_path / "independent_count_law.bngl"
    bng2_source.write_text(_independent_bng2_source(), encoding="utf-8")
    translated = subprocess.run(
        [os.environ.get("PERL", "perl"), configured_bng2, str(bng2_source)],
        cwd=tmp_path,
        capture_output=True,
        text=True,
        timeout=60,
        check=False,
    )
    assert translated.returncode == 0, translated.stdout + translated.stderr
    bng2_xml = tmp_path / "independent_count_law.xml"
    assert bng2_xml.is_file(), "independent BNG2 produced no XML"

    direct_counts = []
    native_counts = []
    for offset in range(RUNS):
        seed = BASE_SEED + offset
        result = api.load(str(physical_source)).simulate(
            method="nf", t_end=END_TIME, n_steps=1, seed=seed
        )
        trajectory = runner._result_to_trajectory(result)
        assert trajectory.construction_path == "direct"
        direct_counts.append(_a_count(trajectory.data, trajectory.columns))

        gdat, error = oracle_nfsim.run_nfsim(
            bng2_xml,
            tmp_path / f"native_{seed}",
            t_end=END_TIME,
            n_steps=1,
            seed=seed,
        )
        assert gdat is not None, error
        data, columns = compare.parse_gdat(gdat)
        assert data is not None and columns is not None
        native_counts.append(_a_count(data, columns))

    _assert_binomial_count_marginal(direct_counts)
    _assert_binomial_count_marginal(native_counts)


