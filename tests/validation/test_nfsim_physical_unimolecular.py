def _bimolecular_conversion_count(trajectory_data, columns) -> int:
    assert "A_count" in columns
    assert "B_count" in columns
    assert "C_count" in columns
    a = trajectory_data[-1, columns.index("A_count")]
    b = trajectory_data[-1, columns.index("B_count")]
    c = trajectory_data[-1, columns.index("C_count")]
    assert a + c == BIMOLECULAR_INITIAL
    assert b + c == BIMOLECULAR_INITIAL
    return int(c)
