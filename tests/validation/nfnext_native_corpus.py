"""Full network-free corpus evidence for the NFnext production entry point.

This module is the validation *harness* for issue #148's
``release-nfnext-execution`` check.  It does not implement or re-implement any
NFnext semantics: the subject is the production binding
``cpp.simulate_nfnext(cpp.parse_string(source), times, seed=...)``, and the
oracle is the pinned native NFsim binary fed BNG-XML generated by the pinned
BNG2.  Every TIER_NF model is attempted with the same declared protocol; no
model is dropped once results are visible.

Honesty rules implemented here:

* ``NOT_TESTED`` is produced only when an independent oracle is unavailable,
  and is never counted as a pass.  In strict CI the caller turns that into a
  hard failure through ``strict.require_oracle``.
* A model that NFnext refuses is ``UNSUPPORTED``; a model that cannot finish a
  run inside the declared wall-clock budget is ``TIMEOUT``; neither can become
  ``PASS`` by shrinking the corpus or by comparing fewer observables.
* The seed budget, sample grid, oracle paths and wall-clock budget are fixed in
  a ``plan`` block *before* the first execution, so later filtering is visible.
* Each NFnext sample is produced in a fresh interpreter that loads this
  worktree's freshly built extension and calls only ``simulate_nfnext``.  The
  binding's ``engine`` field is checked on every trajectory, which is the
  single-engine (``release-nfnext-routes``) evidence.
"""

