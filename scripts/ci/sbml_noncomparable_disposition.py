#!/usr/bin/env python3
"""Spec-backed NON-COMPARABLE dispositions for the Issue 159 Core coverage gate.

The official SSTS case ``semantic/00965`` uses two competing events (``Qinc``
and ``Rinc``) that share a trigger, a priority value and a delay.  Both triggers
are non-persistent and each event resets the shared ``reset`` parameter, so
exactly one of them executes at each instant.  SBML Level 3 Version 2 Core,
Release 2, section 4.12.3 requires equally prioritised simultaneous events to be
executed in a random order, and section 4.12.2 requires a non-persistent trigger
whose expression has become false not to execute.  The published reference is
one draw of that random process, so no deterministic engine can reproduce it
point-wise.

This module is *validation metadata only*.  It never changes a harness verdict,
never turns ``unsupported`` into ``passed`` and never skips a case silently.  A
disposition is emitted only when the report carries the harness-generated reason
byte-for-byte at every site where the harness records it, together with the
specification basis.  Any deviation fails closed.  The reason string below is
generated by ``validate_sbml_test_suite._random_event_execution_verdict``; the
accompanying test proves that identity rather than trusting a transcription.
"""

from __future__ import annotations

from typing import Any

DISPOSITION_STATUS = "NON_COMPARABLE"
DISPOSITION_EVIDENCE_KIND = "specification-non-comparable"

REASON = (
    "the source model's events Qinc, Rinc share one trigger and one priority, "
    "so SBML Level 3 Version 2 Core, Release 2, section 4.12.3 requires them "
    "to be executed in a random order; the official reference is one draw of "
    "that random process, so the case is not comparable point-wise"
)

# Fragments that tie the reason to the specification basis.  All must occur in
# the report's generated reason; this prevents a generic "unsupported" reason
# from qualifying the disposition even if the literal reason check is bypassed.
SPEC_BASIS = (
    "SBML Level 3 Version 2 Core, Release 2, section 4.12.3",
    "executed in a random order",
    "one draw of that random process",
    "not comparable point-wise",
)

# Source semantics established from the pinned suite case
# cases/semantic/00965/00965-sbml-l3v2.xml (suite cf38585f).  This is the reason
# the official reference cannot be compared point-wise; it is not a claim that
# BNG3 executed the reference trajectory.
SOURCE_SEMANTICS = (
    "events Qinc and Rinc share the trigger (time - reset >= 0.01), priority 10 "
    "and no delay, both have persistent=false, and their assignments compete "
    "(each resets 'reset' and increments its own Q/R counter while clearing the "
    "other); L3V2 Core 4.12.3 and 4.12.2 therefore require a random choice of "
    "which event executes",
)

PINNED_CASES = {
    ("sbml.core.Priority.math", "semantic", "00965"): {
        "status": "unsupported",
        "reason": REASON,
        "spec_basis": SPEC_BASIS,
        "source_semantics": SOURCE_SEMANTICS,
    }
}


def disposition_id(category: str, case_id: str) -> str:
    return f"non-comparable:{category}/{case_id}"


def classify(
    row: str, category: str, case_id: str, record: dict[str, Any] | None
) -> dict[str, Any] | None:
    """Return a disposition row for a pinned case, or ``None`` if not pinned.

    Raises ``ValueError`` when the pinned case is missing, changes status, loses
    the generated reason at any recording site, or no longer names the spec
    basis.  A genuine ``failed``/``timeout`` case therefore cannot be laundered
    into a disposition, and a changed reason cannot be silently accepted.
    Non-pinned cases are left to the caller's ordinary pass/fail coverage rule.
    """
    pin = PINNED_CASES.get((row, category, case_id))
    if pin is None:
        return None
    identity = f"{row}: {category}/{case_id}"
    if record is None:
        raise ValueError(f"{identity}: pinned non-comparable case is missing")
    if record.get("status") != pin["status"]:
        raise ValueError(
            f"{identity}: pinned non-comparable case status "
            f"{record.get('status')!r} != {pin['status']!r}"
        )
    official = record.get("official_conformance") or {}
    if official.get("status") != "unsupported":
        raise ValueError(
            f"{identity}: official_conformance.status "
            f"{official.get('status')!r} is not unsupported"
        )
    for site, actual in (
        ("official_conformance.reason", official.get("reason")),
        ("unsupported_reason", record.get("unsupported_reason")),
        (
            "simulation_comparison.skip_reason",
            (record.get("simulation_comparison") or {}).get("skip_reason"),
        ),
    ):
        if actual != pin["reason"]:
            raise ValueError(
                f"{identity}: harness reason at {site} is not the pinned "
                "harness-generated reason"
            )
    if (record.get("simulation_comparison") or {}).get("skipped") is not True:
        raise ValueError(f"{identity}: point-wise comparison is not marked skipped")
    reason = official["reason"]
    missing = [fragment for fragment in pin["spec_basis"] if fragment not in reason]
    if missing:
        raise ValueError(f"{identity}: reason lost spec basis: {missing}")
    return {
        "id": disposition_id(category, case_id),
        "status": DISPOSITION_STATUS,
        "stage": "issue159-release-receipt",
        "check": "release-ssts-coverage",
        "related_issues": [159],
        "evidence_kind": DISPOSITION_EVIDENCE_KIND,
        "supported_execution": False,
        "counts_as_pass": False,
        "row": row,
        "case": f"{category}/{case_id}",
        "reason": reason,
        "spec_basis": list(pin["spec_basis"]),
        "source_semantics": list(pin["source_semantics"]),
        "detail": (
            "The official reference is one draw of a random event order "
            "required by SBML L3V2 Core 4.12.3; the case is explicitly NOT "
            "comparable point-wise and is neither a pass nor a silent skip."
        ),
    }
